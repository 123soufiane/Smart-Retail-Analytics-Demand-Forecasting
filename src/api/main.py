"""FastAPI application exposing demand forecast data."""

import json
from typing import Literal

import pandas as pd
from fastapi import FastAPI, HTTPException, Query

from src.api.data import (
    DATA_DIR,
    FORECAST_FILES,
    ForecastLevel,
    load_forecasts,
    summarize_forecasts,
)

app = FastAPI(
    title="Smart Retail Demand Forecast API",
    description="Read demand forecasts generated by the project prediction pipeline.",
    version="1.0.0",
)


def _load_or_raise(level: ForecastLevel) -> pd.DataFrame:
    try:
        return load_forecasts(level)
    except FileNotFoundError as error:
        raise HTTPException(status_code=503, detail=str(error)) from error
    except ValueError as error:
        raise HTTPException(status_code=500, detail=str(error)) from error


@app.get("/api/health")
def health() -> dict:
    available = {
        level: (DATA_DIR / filename).is_file()
        for level, filename in FORECAST_FILES.items()
    }
    return {
        "status": "ok" if any(available.values()) else "degraded",
        "available_forecasts": available,
    }


@app.get("/api/summary")
def summary(level: Literal["store", "product"] = "store") -> dict:
    forecasts = _load_or_raise(level)
    return summarize_forecasts(forecasts, level)


@app.get("/api/forecasts")
def forecasts(
    level: Literal["store", "product"] = "store",
    limit: int = Query(default=100, ge=1, le=10000),
) -> dict:
    data = _load_or_raise(level).head(limit)
    records = json.loads(data.to_json(orient="records", date_format="iso"))
    return {"level": level, "count": len(records), "forecasts": records}
